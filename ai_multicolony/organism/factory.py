# ── Factory ──────────────────────────────────────────────────────────────────


class SolutionFactory:
    """Builds solutions from approved decisions.

    Generates code artifacts, service definitions, configuration
    files, and documentation based on build requests.

    Usage::

        factory = SolutionFactory()
        request = BuildRequest(
            decision_id="dec-123",
            signal_title="Create monitoring service",
            artifact_type=ArtifactType.SERVICE,
            requirements=["Monitor API health", "Alert on failures"],
        )
        result = await factory.build(request)
    """

    def __init__(self):
        self._build_count: int = 0
        self._builds: List[BuildResult] = []
        self._custom_templates: Dict[str, str] = {}

    def register_template(self, name: str, template: str) -> None:
        """Register a custom code template."""
        self._custom_templates[name] = template

    async def build(self, request: BuildRequest) -> BuildResult:
        """Build a solution from a request.

        Parameters
        ----------
        request:
            Build request with requirements and constraints.

        Returns
        -------
        BuildResult
            Build result with generated artifacts.
        """
        import time
        start = time.monotonic()
        self._build_count += 1

        result = BuildResult(
            request_id=request.request_id,
            status=BuildStatus.BUILDING,
        )

        try:
            # Select template
            template_name = request.template or self._select_template(request.artifact_type)
            template = self._custom_templates.get(template_name) or CODE_TEMPLATES.get(template_name, "")

            if not template:
                result.status = BuildStatus.FAILED
                result.errors.append(f"No template found for '{template_name}'")
                result.duration_ms = (time.monotonic() - start) * 1000
                self._builds.append(result)
                return result

            # Generate artifact
            params = self._prepare_params(request)
            content = self._render_template(template, params)

            artifact = BuildArtifact(
                artifact_type=request.artifact_type,
                name=self._generate_name(request),
                description=f"Auto-generated from decision {request.decision_id}",
                content=content,
                language=self._get_language(request.artifact_type),
                metadata={
                    "decision_id": request.decision_id,
                    "signal_id": request.signal_id,
                    "requirements": request.requirements,
                    "template": template_name,
                },
            )

            # Validate
            result.status = BuildStatus.VALIDATING
            validation_errors = self._validate_artifact(artifact)
            if validation_errors:
                result.warnings.extend(validation_errors)

            result.artifacts.append(artifact)
            result.status = BuildStatus.COMPLETED

        except Exception as e:
            result.status = BuildStatus.FAILED
            result.errors.append(str(e))
            logger.error("Build failed: %s", e)

        result.duration_ms = (time.monotonic() - start) * 1000
        self._builds.append(result)
        return result

    async def build_batch(self, requests: List[BuildRequest]) -> List[BuildResult]:
        """Build multiple solutions."""
        results = []
        for request in requests:
            result = await self.build(request)
            results.append(result)
        return results

    # ── Helpers ─────────────────────────────────────────────────────────

    @staticmethod
    def _select_template(artifact_type: ArtifactType) -> str:
        """Select an appropriate template for the artifact type."""
        template_map = {
            ArtifactType.CODE: "python_module",
            ArtifactType.SERVICE: "service",
            ArtifactType.CONFIG: "config",
            ArtifactType.API_ENDPOINT: "api_endpoint",
            ArtifactType.TEST: "python_module",
            ArtifactType.PIPELINE: "python_module",
            ArtifactType.DOCUMENTATION: "config",
            ArtifactType.DATABASE_MIGRATION: "python_module",
        }
        return template_map.get(artifact_type, "python_module")

    @staticmethod
    def _prepare_params(request: BuildRequest) -> Dict[str, Any]:
        """Prepare template parameters from a build request."""
        title = request.signal_title or "unnamed"
        name_parts = title.replace("-", " ").replace("_", " ").split()
        class_name = "".join(p.capitalize() for p in name_parts) or "GeneratedModule"
        module_name = title.lower().replace(" ", "_").replace("-", "_") or "generated_module"

        return {
            "module_name": module_name,
            "class_name": class_name,
            "class_description": request.signal_title or "Auto-generated class",
            "description": request.signal_title or "Auto-generated by AI-MultiColony",
            "endpoint_name": module_name,
            "request_model": f"{class_name}Request",
            "response_model": f"{class_name}Response",
            "handler_name": f"handle_{module_name}",
            "config_name": class_name,
            "service_name": module_name,
            "service_class": class_name,
            "service_description": request.signal_title or "Auto-generated service",
            "timestamp": datetime.now(timezone.utc).isoformat(),
            **request.parameters,
        }

    @staticmethod
    def _render_template(template: str, params: Dict[str, Any]) -> str:
        """Render a template with parameter substitution."""
        result = template
        for key, value in params.items():
            placeholder = "{" + key + "}"
            result = result.replace(placeholder, str(value))
        return result

    @staticmethod
    def _generate_name(request: BuildRequest) -> str:
        """Generate a name for the artifact."""
        title = request.signal_title or "unnamed"
        return title.lower().replace(" ", "_").replace("-", "_")[:50]

    @staticmethod
    def _get_language(artifact_type: ArtifactType) -> str:
        """Get the programming language for an artifact type."""
        lang_map = {
            ArtifactType.CODE: "python",
            ArtifactType.CONFIG: "ini",
            ArtifactType.SERVICE: "python",
            ArtifactType.API_ENDPOINT: "python",
            ArtifactType.TEST: "python",
            ArtifactType.PIPELINE: "python",
            ArtifactType.DOCUMENTATION: "markdown",
            ArtifactType.DATABASE_MIGRATION: "python",
        }
        return lang_map.get(artifact_type, "text")

    @staticmethod
    def _validate_artifact(artifact: BuildArtifact) -> List[str]:
        """Validate a built artifact."""
        warnings: List[str] = []
        if not artifact.content:
            warnings.append("Empty content")
        if not artifact.name:
            warnings.append("Missing artifact name")
        if len(artifact.content) < 10:
            warnings.append("Content too short (possible template rendering issue)")
        return warnings

    @property
    def stats(self) -> Dict[str, Any]:
        """Factory statistics."""
        total = len(self._builds)
        completed = sum(1 for b in self._builds if b.status == BuildStatus.COMPLETED)
        failed = sum(1 for b in self._builds if b.status == BuildStatus.FAILED)
        return {
            "build_count": self._build_count,
            "total_builds": total,
            "completed": completed,
            "failed": failed,
            "success_rate": completed / max(1, total),
            "templates": list(CODE_TEMPLATES.keys()) + list(self._custom_templates.keys()),
        }
