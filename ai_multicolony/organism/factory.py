"""Solution builder (Factory) for the AI-MultiColony organism.

Implements the Factory phase of the organism lifecycle: building
solutions, generating code, and creating services in response
to approved decisions.

The factory supports multiple output types: code artifacts,
configuration files, service definitions, and documentation.
"""

from __future__ import annotations

import logging
import uuid
from datetime import datetime, timezone
from enum import Enum
from typing import Any, Dict, List, Optional

from pydantic import BaseModel, Field, ConfigDict

logger = logging.getLogger(__name__)


# ── Enums ────────────────────────────────────────────────────────────────────


class ArtifactType(str, Enum):
    """Type of built artifact."""
    CODE = "code"
    CONFIG = "config"
    SERVICE = "service"
    DOCUMENTATION = "documentation"
    TEST = "test"
    PIPELINE = "pipeline"
    API_ENDPOINT = "api_endpoint"
    DATABASE_MIGRATION = "database_migration"


class BuildStatus(str, Enum):
    """Status of a build."""
    PENDING = "pending"
    BUILDING = "building"
    COMPLETED = "completed"
    FAILED = "failed"
    VALIDATING = "validating"
    DEPLOYED = "deployed"


# ── Models ───────────────────────────────────────────────────────────────────


class BuildArtifact(BaseModel):
    """A built artifact from the factory."""
    model_config = ConfigDict(frozen=False)

    artifact_id: str = Field(default_factory=lambda: uuid.uuid4().hex[:12])
    artifact_type: ArtifactType = ArtifactType.CODE
    name: str = ""
    description: str = ""
    content: str = ""
    language: str = "python"
    version: str = "1.0.0"
    dependencies: List[str] = Field(default_factory=list)
    metadata: Dict[str, Any] = Field(default_factory=dict)
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class BuildRequest(BaseModel):
    """A request to build a solution."""
    model_config = ConfigDict(frozen=False)

    request_id: str = Field(default_factory=lambda: uuid.uuid4().hex[:12])
    decision_id: str = ""
    signal_id: str = ""
    signal_title: str = ""
    artifact_type: ArtifactType = ArtifactType.CODE
    requirements: List[str] = Field(default_factory=list)
    constraints: Dict[str, Any] = Field(default_factory=dict)
    template: str = ""
    parameters: Dict[str, Any] = Field(default_factory=dict)


class BuildResult(BaseModel):
    """Result from a build operation."""
    model_config = ConfigDict(frozen=False)

    build_id: str = Field(default_factory=lambda: uuid.uuid4().hex[:12])
    request_id: str = ""
    status: BuildStatus = BuildStatus.PENDING
    artifacts: List[BuildArtifact] = Field(default_factory=list)
    errors: List[str] = Field(default_factory=list)
    warnings: List[str] = Field(default_factory=list)
    duration_ms: float = 0.0
    timestamp: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))

    @property
    def success(self) -> bool:
        return self.status == BuildStatus.COMPLETED and len(self.artifacts) > 0


